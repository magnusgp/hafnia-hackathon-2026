// Save the review request for a live assessment and send its one event through the app's own dialogs.
// Usage: bun live-send.mjs <outDir> <caseId> [baseUrl]. The request is saved without a human verdict (no attestation).
import { chromium } from 'playwright';
import { mkdir, rename } from 'node:fs/promises';
const out = process.argv[2], id = process.argv[3], base = process.argv[4] ?? 'http://127.0.0.1:8780';
await mkdir(out).catch(() => {});
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--no-first-run'] });
const ctx = await browser.newContext({ viewport: { width: 1920, height: 1080 }, recordVideo: { dir: out, size: { width: 1920, height: 1080 } } });
const page = await ctx.newPage();
const t0 = Date.now(), log = m => console.log(((Date.now() - t0) / 1000).toFixed(1), m);
await page.goto(`${base}/#/${id}`, { waitUntil: 'networkidle' });
await page.waitForSelector('video');
await page.waitForTimeout(3000);
await page.getByRole('button', { name: 'Send to XProtect review' }).click();
await page.getByLabel('Note').fill('Requested by the Claude demo reviewer after watching the recording. AI request, not a human verdict.');
await page.getByLabel('I watched the relevant footage').check();
await page.waitForTimeout(1200);
await page.getByRole('button', { name: 'Save review request' }).click();
await page.getByRole('dialog').waitFor({ state: 'detached' });
log('request saved');
await page.waitForTimeout(2000);
await page.getByRole('button', { name: 'Send to XProtect', exact: true }).click();
const dlg = page.getByRole('dialog');
await dlg.getByText('Fingerprint').waitFor();
log('preview: ' + (await dlg.innerText()).replace(/\n+/g, ' | ').slice(0, 500));
await page.waitForTimeout(2500);
await dlg.getByLabel('Send this one event to XProtect').check();
await dlg.getByRole('button', { name: 'Send event' }).click();
await dlg.waitFor({ state: 'detached', timeout: 30000 });
await page.waitForTimeout(2500);
log('native: ' + (await page.locator('.native').innerText()));
await page.screenshot({ path: `${out}/live-sent.png` });
const video = page.video();
await ctx.close(); await browser.close();
await rename(await video.path(), `${out}/live-send.webm`);
