// Exercises the prototype in a real browser: playback, seeking, the decision form, drawers, region dragging, the New Watch flow.
// Usage: bun design/gate2/interact.mjs <a|b>
import { chromium } from '../../frontend/node_modules/playwright/index.mjs';
const comp = process.argv[2];
const base = new URL(`./${comp}.html`, import.meta.url).href;
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--no-first-run', '--autoplay-policy=no-user-gesture-required'] });
let fails = 0;
const ok = (n, c, x = '') => { if (!c) { fails++; console.log('FAIL', n, x); } else console.log('ok  ', n); };
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const problems = [];
page.on('console', (m) => m.type() === 'error' && problems.push(m.text()));
page.on('pageerror', (e) => problems.push(e.message));
const t = () => page.evaluate(() => document.querySelector('video').currentTime);
const body = () => page.locator('body').innerText();

await page.goto(base + '#/exceptions');
await page.waitForFunction(() => document.querySelector('video')?.readyState >= 2);
ok('first thing on screen names the event', (await page.locator('h1').first().innerText()) === 'Person on the track area');
ok('one occurrence in the queue, not four', (await page.locator('.item[aria-current], .occ').count()) === 1);
ok('alarm 10 shown as the native outcome', /Alarm 10/.test(await body()));
ok('no ordinary Send button for the alerted occurrence', (await page.getByRole('button', { name: /^send/i }).count()) === 0);
await page.locator('[data-seek]').filter({ hasText: /steps down/i }).first().click();
await page.waitForTimeout(400);
ok('"steps down" jumps to 6.4 s', Math.abs((await t()) - 6.4) < 0.15, String(await t()));
ok('detector box visible while the person is at the region', (await page.locator('.ov .box').count()) === 1);
await page.locator('[data-seek="0"]').first().click();
await page.waitForTimeout(300);
ok('no detector box before the person reaches the region', (await page.locator('.ov .box').count()) === 0);
await page.locator('[data-act=play]').click();
await page.waitForTimeout(900);
ok('play advances the clock', (await t()) > 0.5, String(await t()));
await page.locator('[data-act=play]').click();
const sc = comp === 'a' ? '#tl' : '#scrub';
const bb = await page.locator(sc).boundingBox();
const x75 = comp === 'a' ? bb.x + 12 + 0.75 * (bb.width - 24) : bb.x + bb.width * 0.75;
await page.mouse.click(x75, bb.y + bb.height / 2);
await page.waitForTimeout(400);
ok('clicking the timeline seeks (about 9 s)', Math.abs((await t()) - 9) < 0.7, String(await t()));

const rec = page.locator('#rec');
ok('record is disabled at first', await rec.isDisabled());
await page.getByRole('button', { name: 'Yes', exact: true }).click();
ok('still disabled with a verdict only', await rec.isDisabled());
await page.locator('#note').fill('Person lowers off the edge');
ok('still disabled without the watched confirmation', await rec.isDisabled());
await page.locator('#watched').check();
ok('enabled when complete', await rec.isEnabled());
await rec.click();
ok('says nothing was saved', /Nothing was saved/.test(await page.locator('#done').innerText()));

const before = await t();
await page.getByRole('button', { name: /History|All observations/ }).first().click();
await page.waitForTimeout(800);
const h = await page.locator('.drawer').innerText();
ok('history lists four observations', (h.match(/Hafnia: no entry seen/g) || []).length === 4);
ok('history shows revision 1 as an unrecoverable gap', /Revision 1/.test(h) && /cannot be reconstructed/.test(h));
ok('history keeps revision 2 with the AI reviewer named', /Revision 2/.test(h) && /not a human/.test(h));
await page.getByRole('button', { name: 'Close', exact: true }).click();
await page.waitForTimeout(600);
ok('typed note survives the drawer', (await page.locator('#note').inputValue()) === 'Person lowers off the edge');
ok('playhead survives the drawer', Math.abs((await t()) - before) < 0.6, `${before} -> ${await t()}`);
await page.getByRole('button', { name: /^Evidence/ }).first().click();
await page.waitForTimeout(500);
ok('evidence view holds the hashes', /[0-9a-f]{64}/.test(await page.locator('.drawer').innerText()));
await page.goto(base + '#/exceptions/alert');
await page.waitForTimeout(500);
const al = await page.locator('.drawer').innerText();
ok('alert view: accepted, alarm 10, verified by the product owner', /accepted/i.test(al) && /Alarm 10/.test(al) && /product owner/.test(al));
ok('a repeat alert needs an acknowledgement, disabled here', await page.locator('.drawer input[type=checkbox]').isDisabled());

await page.goto(base + '#/watches');
await page.waitForTimeout(300);
const wt = await body();
ok('no Watch is called active, running or monitoring', !/\b(active|running|monitoring)\b/i.test(wt));
ok('paused, off and both failures are stated', /Paused/.test(wt) && /Off/.test(wt) && /Could not check/.test(wt) && /Hafnia step could not run/.test(wt));

await page.goto(base + '#/watch/w-c95bfc089f?step=2');
await page.waitForSelector('.handle');
const hdl = page.locator('.handle').nth(1);
const hb = await hdl.boundingBox();
await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2);
await page.mouse.down();
await page.mouse.move(hb.x - 60, hb.y - 40, { steps: 5 });
await page.mouse.up();
const hb2 = await hdl.boundingBox();
ok('dragging a region point moves it', Math.abs(hb2.x - hb.x) > 30, `${hb.x} -> ${hb2.x}`);

await page.goto(base + '#/watch/new');
await page.waitForTimeout(300);
await page.locator('[data-cam="busy_street"]').click();
ok('a camera without a frame gets a compact action', (await page.getByRole('button', { name: 'Get a frame' }).count()) === 1 && (await page.locator('.noframe').evaluate((e) => e.getBoundingClientRect().height)) < 160);
await page.getByRole('button', { name: 'Get a frame' }).click();
ok('the failure state is actionable', /Check that the camera is recording/.test(await page.locator('.noframe').innerText()));
await page.locator('[data-cam="person_on_railway_tracks"]').click();
await page.waitForSelector('.redit img');
ok('a camera with a frame shows it in step 1', (await page.locator('.redit img').count()) === 1 && /frame Ortru will observe/.test(await page.locator('#legend').innerText()));
await page.locator('[data-step="2"]').first().click();
ok('step 2 asks for the region', /outline the area/i.test(await page.locator('#legend').innerText()));
const rb = await page.locator('.redit').boundingBox();
for (const [fx, fy] of [[0.25, 0.32], [0.99, 0.67], [0.62, 0.99]]) await page.mouse.click(rb.x + rb.width * fx, rb.y + rb.height * fy);
await page.mouse.click(rb.x + rb.width * 0.25, rb.y + rb.height * 0.32);
ok('three points and a closing click make a region', /outlined area/i.test(await page.locator('#legend').innerText()), await page.locator('#legend').innerText());
await page.locator('#q').fill('A person climbs down from the platform edge onto the track area, or stays on the tracks.');
ok('the condition label is derived from the question', (await page.locator('#lab').inputValue()) === 'Person climbs down from the platform edge onto the track area', await page.locator('#lab').inputValue());
await page.locator('#lab').fill('Person on the track area');
await page.locator('#q').fill('Anyone on the track. Then more.');
ok('a corrected label is not overwritten', (await page.locator('#lab').inputValue()) === 'Person on the track area');
ok('unavailable detectors are not offered', !/stationarity|left in place/i.test(await body()));
ok('no console or page errors', problems.length === 0, problems.join(' | '));
await browser.close();
console.log(fails ? `${fails} failed` : 'all passed');
process.exit(fails ? 1 : 0);
